import Anthropic from "@anthropic-ai/sdk";
import { NextResponse } from "next/server";

export const dynamic = "force-dynamic";

export async function POST(request: Request) {
  try {
    const apiKey = process.env.ANTHROPIC_API_KEY;
    if (!apiKey) {
      return NextResponse.json(
        { error: "ANTHROPIC_API_KEY не настроен" },
        { status: 500 }
      );
    }

    const anthropic = new Anthropic({ apiKey });
    const { description, audience, platforms, weeks, voice } =
      await request.json();

    if (!description || !audience || !platforms?.length) {
      return NextResponse.json(
        { error: "Необходимо указать описание, аудиторию и хотя бы одну платформу" },
        { status: 400 }
      );
    }

    const totalDays = weeks * 7;

    const voiceMap: Record<string, string> = {
      Professional: "профессиональном",
      Casual: "неформальном",
      Bold: "смелом",
      Friendly: "дружелюбном",
    };
    const voiceRu = voiceMap[voice] || voice;

    const message = await anthropic.messages.create({
      model: "claude-sonnet-4-20250514",
      max_tokens: 4096,
      system: `Ты — эксперт по стратегии социальных сетей. Твоя задача — создавать вовлекающий контент, который наращивает аудиторию, повышает вовлечённость и поддерживает бизнес-цели.

ВАЖНО: Весь контент (topic, caption, cta, goal, expectedMetrics) должен быть НА РУССКОМ ЯЗЫКЕ. Хэштеги могут быть как на русском, так и на английском.

Ты используешь следующие фреймворки:

КОНТЕНТ-СТОЛПЫ: Создай 3-5 контент-столпов с процентным распределением. Примеры:
- 30% Отраслевые инсайты и тренды
- 25% Закулисье и культура
- 25% Обучающий контент и инструкции
- 15% Личные истории и ценности
- 5% Промо и спецпредложения

ФОРМУЛЫ ХУКОВ для каждого поста:
- Любопытство: "Большинство людей не знают этого о [тема]..."
- История: "На прошлой неделе произошло кое-что, что изменило моё отношение к [тема]..."
- Ценность: "Вот 3 способа [достичь результата] без [типичная боль]..."
- Контрарный: "Все говорят, что [общее мнение]. Вот почему это неправда..."

РЕКОМЕНДАЦИИ ПО ПЛАТФОРМАМ:
- Facebook: 3-5 раз/неделю, микс из картинок, ссылок, видео. Длинные подписи допустимы.
- Instagram: 4-7 раз/неделю, Reels, карусели, Stories. Визуал-первый, хэштеги важны.
- LinkedIn: 3-5 раз/неделю, текстовые посты, статьи, документы. Профессиональный тон, сторителлинг.
- TikTok: 3-7 раз/неделю, короткие видео, тренды, закулисье. Неформальный, аутентичный тон.

Всегда чередуй типы контента между днями и платформами. Распределяй столпы согласно процентам.`,
      messages: [
        {
          role: "user",
          content: `Создай контент-план на ${totalDays} дней для этого бизнеса:

Бизнес: ${description}
Целевая аудитория: ${audience}
Платформы: ${platforms.join(", ")}
Тон общения: ${voiceRu}
Длительность: ${weeks} недел${weeks === 1 ? "я" : weeks < 5 ? "и" : "ь"} (${totalDays} дней)

Сгенерируй ровно ${totalDays} постов, распределённых по выбранным платформам.

Верни ТОЛЬКО JSON-объект (без markdown, без блоков кода) со следующей структурой:
{
  "posts": [
    {
      "day": 1,
      "platform": "Instagram",
      "contentType": "Reel",
      "topic": "Закулисье утренней тренировки",
      "caption": "Текст подписи к посту...",
      "hashtags": "#фитнес #сайклинг #мотивация",
      "cta": "Запишитесь на бесплатное пробное занятие по ссылке в био",
      "goal": "Вовлечённость",
      "expectedMetrics": "800-1.2К просмотров, 50-80 сохранений"
    }
  ]
}

Описание полей:
- "cta": Конкретный призыв к действию — что вы хотите, чтобы люди СДЕЛАЛИ после просмотра поста. Примеры: "Напишите в комментариях ваше любимое упражнение", "Переходите по ссылке в био для записи", "Отправьте другу, которому это нужно", "Напишите нам в директ", "Сохраните на потом"
- "goal": Одно из: Узнаваемость, Вовлечённость, Лиды, Продажи, Удержание. Выбери ОСНОВНУЮ цель поста.
- "expectedMetrics": Реалистичные ожидаемые метрики для малого-среднего бизнеса. Включи 2-3 метрики: просмотры, охват, сохранения, клики, лиды, репосты, комментарии, конверсии. Используй диапазоны (например "500-800 просмотров, 20-40 сохранений"). Учитывай платформу — Instagram Reels дают больше просмотров, LinkedIn больше кликов и т.д.

Правила:
- Распределяй посты равномерно по платформам
- Чередуй типы контента (Reel, Карусель, Story, Текст, Картинка, Видео, Статья и т.д.)
- Каждая подпись должна быть готова к публикации — написана в ${voiceRu} тоне
- Хэштеги должны соответствовать платформе (пропускай для LinkedIn)
- Следуй распределению контент-столпов
- Используй формулы хуков для начала подписей
- Чередуй цели — не каждый пост должен быть про продажи, включай посты для узнаваемости и вовлечённости
- CTA должны быть конкретными и побуждающими к действию, не общими
- ВСЁ должно быть на РУССКОМ ЯЗЫКЕ`,
        },
      ],
    });

    const textBlock = message.content.find((b) => b.type === "text");
    if (!textBlock || textBlock.type !== "text") {
      return NextResponse.json(
        { error: "Нет текстового ответа от Claude" },
        { status: 500 }
      );
    }

    const jsonMatch = textBlock.text.match(/{[\s\S]*}/);
    if (!jsonMatch) {
      return NextResponse.json(
        { error: "Не удалось распарсить ответ как JSON" },
        { status: 500 }
      );
    }

    const result = JSON.parse(jsonMatch[0]);
    return NextResponse.json(result);
  } catch (error) {
    console.error("Content plan error:", error);
    return NextResponse.json(
      {
        error:
          error instanceof Error
            ? error.message
            : "Не удалось сгенерировать контент-план",
      },
      { status: 500 }
    );
  }
}
